// Runs the checkout agent from the command line.
//
//   npm run test-page                                  local test store with two common flaws switched on
//   npm run test-page -- --clean                       local test store with no flaws
//   npm run check -- --url https://store.example --shop store.myshopify.com --query "jacket"
//
// Options: --video-dir <dir> (default ./videos; videos are never committed), --no-video,
// --write-sample <file> (writes the run as the TypeScript sample the screens show).
// With DATABASE_URL set, the run is stored in checkout_runs.
import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { getDb, saveCheckoutRun, type CheckoutRunResult } from "@centurion/core/server";
import { runCheckoutAgent } from "./agent.ts";
import { startTestStore } from "./test-store.ts";

function arg(name: string): string | undefined {
  const i = process.argv.indexOf(`--${name}`);
  const value = i === -1 ? undefined : process.argv[i + 1];
  if (i !== -1 && (value === undefined || value.startsWith("--"))) throw new Error(`--${name} needs a value.`);
  return value;
}
const flag = (name: string) => process.argv.includes(`--${name}`);

const MARK = { passed: "✓", slowed: "!", blocked: "✕" } as const;

function print(run: CheckoutRunResult) {
  console.log(`\n${run.target.kind === "test_page" ? "Test page" : "Storefront"}: ${run.target.url}`);
  for (const s of run.steps) {
    console.log(`${MARK[s.status]} ${s.n}. ${s.title} (${(s.ms / 1000).toFixed(1)} s): ${s.detail}${s.hint ? `\n     Fix: ${s.hint}` : ""}`);
  }
  console.log(
    run.result === "reached_checkout" ? `Reached checkout, stopped before payment. ${run.problems} problem(s).` : `Blocked at step ${run.failedStep}.`
  );
  if (run.blockedRequests.length) console.log(`Payment guard stopped: ${run.blockedRequests.join(", ")}`);
  if (run.videoPath) console.log(`Video: ${run.videoPath}`);
}

function sampleSource(run: CheckoutRunResult): string {
  const sample = { ...run, videoPath: null };
  return `// A real Agent Checkout Test run on the local test page (packages/checkout-test/src/test-store.ts), with the
// popup and unlabeled size picker switched on. Generated by \`npm run test-page -- --write-sample\` in
// packages/checkout-test. It is a test-page run, not a real store, and every screen that shows it says so.
import type { CheckoutRunResult } from "./checkout-types.ts";

export const TEST_PAGE_CHECKOUT_RUN: CheckoutRunResult = ${JSON.stringify(sample, null, 2)};
`;
}

async function main() {
  const testPage = flag("test-page");
  const url = arg("url");
  if (!testPage && !url) throw new Error("Pass --test-page or --url <storefront>.");
  const videoDir = flag("no-video") ? null : resolve(arg("video-dir") ?? "videos");

  const store = testPage ? await startTestStore(flag("clean") ? {} : { popup: true, unlabeledSize: true }) : null;
  try {
    const run = await runCheckoutAgent({
      url: store?.url ?? url!,
      kind: testPage ? "test_page" : "storefront",
      query: arg("query") ?? (testPage ? "trail jacket" : undefined),
      videoDir
    });
    print(run);

    const out = arg("write-sample");
    if (out) {
      await writeFile(resolve(out), sampleSource(run));
      console.log(`Wrote ${out}`);
    }
    const db = getDb();
    if (db) {
      const shop = arg("shop");
      const id = await saveCheckoutRun(db, { shop: testPage || !shop ? null : { domain: shop }, run });
      console.log(`Stored checkout run ${id}`);
    }
    process.exitCode = run.result === "reached_checkout" ? 0 : 1;
  } finally {
    await store?.close();
  }
}

main().then(
  () => process.exit(),
  error => {
    console.error(error instanceof Error ? error.message : error);
    process.exit(2);
  }
);
